// Binary gvisor-installer installs gVisor on a Kubernetes node. It runs in a
// privileged DaemonSet pod with the host root filesystem mounted.
//
// Modes:
//
//	run                Install or uninstall, per $MODE, then wait for SIGTERM.
//	trigger-uninstall  Switch the DaemonSet to uninstall mode and wait until
//	                   all nodes are clean.
//	probe              Readiness probe: succeed if "run" has finished.
package main

import (
	"crypto/sha256"
	"encoding/hex"
	"errors"
	"fmt"
	"io"
	"log"
	"os"
	"os/exec"
	"os/signal"
	"path/filepath"
	"regexp"
	"strings"
	"syscall"
	"time"
)

const (
	readyFile    = "/tmp/gvisor-deploy-ready"
	nodeLabel    = "gvisor.dev/runsc"
	modeAnnot    = "gvisor.dev/deploy-mode"
	shimBinary   = "containerd-shim-runsc-v1"
	runscBinary  = "runsc"
	versionsDir  = "versions"
	currentLink  = "bin"
	defaultAddr  = "/run/containerd/containerd.sock"
	createdDirs  = "created-dirs"
	createdFiles = "created-files"
	configBackup = "config-backup"
	// restartPending exists while a containerd restart is pending.
	restartPending = "restart-pending"
	// stagingPrefix prefixes version directories that are being copied.
	stagingPrefix = ".staging-"
	// trashPrefix prefixes version directories that are being removed. It
	// starts with stagingPrefix, so that gcVersions skips them as versions.
	trashPrefix = stagingPrefix + "removed-"
	// generatedHeader starts the files that the installer writes.
	generatedHeader = "# Generated by gvisor-deploy."
	readyTimeout    = 2 * time.Minute
)

// config is the installer configuration. All paths except hostRoot and
// artifacts are as seen from the host.
type config struct {
	hostRoot       string
	artifacts      string
	installDir     string
	containerdConf string
	runscConf      string
	handler        string
	runscFlags     []string
	podAnnotations []string
	restartCmd     []string
	nodeName       string
	rt             *runtimeTarget
	// restart restarts containerd and checks its health; healthy only
	// checks its health. Tests replace them.
	restart func(c *config, wantBlock bool) error
	healthy func(c *config) error
}

func env(name, def string) string {
	if v := os.Getenv(name); v != "" {
		return v
	}
	return def
}

func loadConfig() config {
	return config{
		hostRoot:       env("HOST_ROOT", "/host"),
		artifacts:      env("ARTIFACTS_DIR", "/opt/gvisor-artifacts"),
		installDir:     env("INSTALL_DIR", "/opt/gvisor"),
		containerdConf: env("CONTAINERD_CONFIG", "/etc/containerd/config.toml"),
		runscConf:      env("RUNSC_CONFIG_PATH", "/etc/gvisor/runsc.toml"),
		handler:        env("RUNTIME_HANDLER", "runsc"),
		runscFlags:     strings.Split(os.Getenv("RUNSC_FLAGS"), "\n"),
		podAnnotations: podAnnotations(),
		restartCmd:     strings.Fields(os.Getenv("RESTART_COMMAND")),
		nodeName:       os.Getenv("NODE_NAME"),
		restart:        restartRuntime,
		healthy:        criHealthy,
	}
}

// podAnnotations returns the pod annotations that containerd passes to runsc.
// An empty POD_ANNOTATIONS passes none.
func podAnnotations() []string {
	if v, ok := os.LookupEnv("POD_ANNOTATIONS"); ok {
		return strings.Fields(v)
	}
	return []string{"dev.gvisor.*"}
}

// host returns the path in the installer's mount namespace for a host path.
func (c *config) host(p string) string {
	return filepath.Join(c.hostRoot, p)
}

func main() {
	log.SetFlags(log.LstdFlags | log.Lmsgprefix)
	log.SetPrefix("gvisor-installer: ")
	if len(os.Args) < 2 {
		log.Fatalf("usage: %s run|trigger-uninstall|probe", os.Args[0])
	}
	switch os.Args[1] {
	case "probe":
		if _, err := os.Stat(readyFile); err != nil {
			os.Exit(1)
		}
	case "run":
		run()
	case "trigger-uninstall":
		if err := triggerUninstall(env("DAEMONSET_NAMESPACE", ""), env("DAEMONSET_NAME", "")); err != nil {
			log.Fatalf("trigger-uninstall failed: %v", err)
		}
	default:
		log.Fatalf("unknown mode %q", os.Args[1])
	}
}

func run() {
	c := loadConfig()
	if c.nodeName == "" {
		log.Fatalf("NODE_NAME is not set")
	}
	kube, err := newKubeClient()
	if err != nil {
		log.Fatalf("cannot create Kubernetes client: %v", err)
	}
	rt, detectErr := detectRuntime(&c)
	if detectErr == nil {
		c.rt = rt
		log.Printf("node %q uses %s; editing %s", c.nodeName, c.rt.name, c.rt.configPath)
	}
	mode := env("MODE", "install")
	switch mode {
	case "install":
		if detectErr != nil {
			err = refusal{detectErr}
		} else {
			err = install(&c, kube)
		}
	case "uninstall":
		if detectErr != nil {
			// The installer refuses such nodes, so it has nothing on them.
			log.Printf("nothing to uninstall: %v", detectErr)
			err = kube.setNodeLabel(c.nodeName, nodeLabel, nil)
		} else {
			err = uninstall(&c, kube)
		}
	default:
		err = fmt.Errorf("unknown MODE %q", mode)
	}
	result := mode + " complete"
	var r refusal
	if errors.As(err, &r) {
		// A refused node must not block the rollout or the uninstall of the
		// other nodes: the pod becomes ready, and the node stays unlabeled.
		log.Printf("NOT INSTALLING gVisor on node %q: %v", c.nodeName, r.error)
		if err = kube.setNodeLabel(c.nodeName, nodeLabel, nil); err != nil {
			log.Fatalf("cannot remove node label: %v", err)
		}
		result = "install refused"
	}
	if err != nil {
		log.Fatalf("%s failed: %v", mode, err)
	}
	if err := os.WriteFile(readyFile, nil, 0644); err != nil {
		log.Fatalf("cannot write ready file: %v", err)
	}
	log.Printf("%s on node %q; waiting for termination", result, c.nodeName)
	sig := make(chan os.Signal, 1)
	signal.Notify(sig, syscall.SIGTERM, syscall.SIGINT)
	<-sig
	// Termination never uninstalls: the pod is also stopped on rolling
	// updates, evictions and node drains. Uninstall uses trigger-uninstall.
}

// handlerRE matches valid RuntimeClass handler names (DNS labels).
var handlerRE = regexp.MustCompile(`^[a-z0-9]([-a-z0-9]{0,61}[a-z0-9])?$`)

// refusal is an error for a node that the installer does not change,
// because the node setup is not supported or conflicts with the install.
type refusal struct{ error }

func install(c *config, kube *kubeClient) error {
	if !handlerRE.MatchString(c.handler) {
		return fmt.Errorf("invalid runtime handler name %q: want a DNS label", c.handler)
	}
	// Do all checks before changing anything on the host.
	if err := checkOwnedFile(c, c.runscConf); err != nil {
		return refusal{err}
	}
	hash, err := artifactsHash(c.artifacts)
	if err != nil {
		return err
	}
	verDir := filepath.Join(c.installDir, versionsDir, hash)
	rc, err := runscConfig(filepath.Join(verDir, runscBinary), c.runscFlags)
	if err != nil {
		return err
	}
	version, err := containerdConfigVersion(c)
	if err != nil {
		return refusal{err}
	}
	block, err := runtimeBlock(version, c.handler, filepath.Join(c.installDir, currentLink, shimBinary), c.runscConf, c.podAnnotations)
	if err != nil {
		return refusal{err}
	}
	setRuntime := func(s string) (string, error) { return setBlock(s, block, c.handler) }
	current := readFileOrEmpty(c.host(c.rt.configPath))
	if current == "" {
		current = c.rt.baseContent
	}
	if _, err := setRuntime(current); err != nil {
		return refusal{err}
	}
	if c.rt.effectivePath != "" {
		// The generated config must not define the handler either.
		if _, err := setBlock(readFileOrEmpty(c.host(c.rt.effectivePath)), block, c.handler); err != nil {
			return refusal{fmt.Errorf("%s: %w", c.rt.effectivePath, err)}
		}
	}
	// The health check after the restart must work before the restart too.
	// Else a node where it cannot work would restart containerd on each run.
	// A pending restart (from an interrupted run) is completed first.
	if _, err := os.Stat(c.host(filepath.Join(c.installDir, restartPending))); err != nil {
		if err := waitHealthy(c, readyTimeout); err != nil {
			return refusal{fmt.Errorf("containerd health check failed before any change: %w", err)}
		}
	}

	// Install the binaries in a directory named after their content, so that
	// existing sandboxes keep their binaries across upgrades.
	if err := installVersion(c, verDir); err != nil {
		return err
	}
	if err := symlinkAtomic(filepath.Join(versionsDir, hash), c.host(filepath.Join(c.installDir, currentLink))); err != nil {
		return err
	}
	// Record host directories that this installer creates, so that
	// uninstall removes them but leaves pre-existing ones in place.
	if err := recordCreatedDirs(c, filepath.Dir(c.runscConf)); err != nil {
		return err
	}
	if _, err := writeFileIfChanged(c.host(c.runscConf), []byte(rc), 0644); err != nil {
		return err
	}
	if err := applyContainerdConfig(c, setRuntime, true); err != nil {
		return err
	}

	gcVersions(c, hash)

	v := "installed"
	if err := kube.setNodeLabel(c.nodeName, nodeLabel, &v); err != nil {
		return fmt.Errorf("cannot label node: %w", err)
	}
	log.Printf("labeled node %q with %s=%s", c.nodeName, nodeLabel, v)
	return nil
}

func uninstall(c *config, kube *kubeClient) error {
	// Remove the label first so that no new gVisor pods land on this node.
	if err := kube.setNodeLabel(c.nodeName, nodeLabel, nil); err != nil {
		return fmt.Errorf("cannot remove node label: %w", err)
	}
	if n := countSandboxes(c); n > 0 {
		log.Printf("WARNING: %d gVisor versions are still in use on this node; their binaries are kept", n)
	}
	if err := applyContainerdConfig(c, removeBlock, false); err != nil {
		return err
	}
	removeCreatedFiles(c)
	if err := checkOwnedFile(c, c.runscConf); err == nil {
		if err := os.Remove(c.host(c.runscConf)); err != nil && !errors.Is(err, os.ErrNotExist) {
			return err
		}
	} else {
		log.Printf("not removing %s: %v", c.runscConf, err)
	}
	removeCreatedDirs(c)
	os.Remove(c.host(filepath.Join(c.installDir, currentLink)))
	gcVersions(c, "")
	if staging, err := filepath.Glob(c.host(filepath.Join(c.installDir, versionsDir, stagingPrefix+"*"))); err == nil {
		for _, d := range staging {
			os.RemoveAll(d)
		}
	}
	os.Remove(c.host(filepath.Join(c.installDir, versionsDir))) // Only succeeds if empty.
	os.Remove(c.host(c.installDir))                             // Only succeeds if empty.
	log.Printf("removed gVisor from node %q", c.nodeName)
	return nil
}

// installVersion installs the release files in verDir. A version directory
// is never changed once it exists: running processes may execute its files,
// and gcVersions finds them by inode.
func installVersion(c *config, verDir string) error {
	if _, err := os.Stat(c.host(verDir)); err == nil {
		log.Printf("binaries already installed in %s", verDir)
		return nil
	}
	staging := filepath.Join(filepath.Dir(verDir), stagingPrefix+filepath.Base(verDir))
	if err := os.RemoveAll(c.host(staging)); err != nil {
		return err
	}
	if err := copyTree(c.artifacts, c.host(staging)); err != nil {
		return err
	}
	if err := os.Rename(c.host(staging), c.host(verDir)); err != nil {
		return err
	}
	log.Printf("installed binaries in %s", verDir)
	return nil
}

// checkOwnedFile fails if path exists and was not written by this installer.
func checkOwnedFile(c *config, path string) error {
	data, err := os.ReadFile(c.host(path))
	if errors.Is(err, os.ErrNotExist) {
		return nil
	} else if err != nil {
		return err
	}
	if !strings.HasPrefix(string(data), generatedHeader) {
		return fmt.Errorf("%s exists and was not created by gvisor-deploy", path)
	}
	return nil
}

func readFileOrEmpty(path string) string {
	data, _ := os.ReadFile(path)
	return string(data)
}

// applyContainerdConfig applies edit to the containerd config and restarts
// containerd if needed.
//
// A marker file records that a restart is pending, so that an installer
// that stops between the config change and the restart restarts containerd
// on its next run. If containerd does not come back healthy, the previous
// config is restored.
func applyContainerdConfig(c *config, edit func(string) (string, error), wantBlock bool) error {
	marker := c.host(filepath.Join(c.installDir, restartPending))
	backup := c.host(filepath.Join(c.installDir, configBackup))
	path := c.host(c.rt.configPath)
	_, err := os.Stat(marker)
	pending := err == nil
	// The config before the change is kept on the host until containerd is
	// healthy, so that a run after an interrupted one can still restore it.
	// The backup file starts with "1" if the config existed, else "0".
	if !pending {
		state := "0"
		if _, err := os.Stat(path); err == nil {
			state = "1" + readFileOrEmpty(path)
		}
		if err := os.MkdirAll(filepath.Dir(backup), 0755); err != nil {
			return err
		}
		if _, err := writeFileIfChanged(backup, []byte(state), 0600); err != nil {
			return err
		}
		if err := os.WriteFile(marker, nil, 0644); err != nil {
			return err
		}
	}
	state := readFileOrEmpty(backup)
	existed, old := strings.HasPrefix(state, "1"), strings.TrimPrefix(state, "1")
	done := func() error {
		os.Remove(backup)
		return os.Remove(marker)
	}
	changed, err := editContainerdConfig(c, edit)
	if err != nil {
		return err
	}
	if !changed && !pending {
		log.Printf("containerd config unchanged; not restarting containerd")
		return done()
	}
	if err := c.restart(c, wantBlock); err != nil {
		if state == "" {
			return err
		}
		log.Printf("containerd is not healthy after the config change (%v); restoring the previous config", err)
		if existed {
			if _, werr := writeFileIfChanged(path, []byte(old), fileMode(path)); werr != nil {
				return fmt.Errorf("%w; restoring the previous config failed: %v", err, werr)
			}
		} else if rerr := os.Remove(path); rerr != nil && !errors.Is(rerr, os.ErrNotExist) {
			return fmt.Errorf("%w; removing the new config failed: %v", err, rerr)
		}
		if rerr := c.restart(c, strings.Contains(old, blockBegin)); rerr != nil {
			return fmt.Errorf("%w; containerd is still unhealthy with the previous config: %v", err, rerr)
		}
		done()
		if !wantBlock {
			// An uninstall that did not happen must not look done: the pod
			// stays not ready, and the cleanup Job reports the node.
			return fmt.Errorf("containerd was not healthy without the gvisor-deploy block, which was restored: %w", err)
		}
		// The node works again with its previous config. Retrying the same
		// change would take containerd down on each run.
		return refusal{fmt.Errorf("containerd was not healthy with the new config, which was rolled back: %w", err)}
	}
	return done()
}

func fileMode(path string) os.FileMode {
	if st, err := os.Stat(path); err == nil {
		return st.Mode().Perm()
	}
	return 0644
}

func createdListFile(c *config, list string) string {
	return c.host(filepath.Join(c.installDir, list))
}

// recordCreated adds a host path to a list of paths that the installer
// created.
func recordCreated(c *config, list, path string) error {
	data, err := os.ReadFile(createdListFile(c, list))
	if err != nil && !errors.Is(err, os.ErrNotExist) {
		return err
	}
	paths := strings.Fields(string(data))
	for _, p := range paths {
		if p == path {
			return nil
		}
	}
	paths = append(paths, path)
	if err := os.MkdirAll(filepath.Dir(createdListFile(c, list)), 0755); err != nil {
		return err
	}
	_, err = writeFileIfChanged(createdListFile(c, list), []byte(strings.Join(paths, "\n")+"\n"), 0644)
	return err
}

// recordCreatedDirs creates the given host directories if needed, and adds
// the ones it creates to the created-dirs list.
func recordCreatedDirs(c *config, dirs ...string) error {
	for _, d := range dirs {
		if _, err := os.Stat(c.host(d)); err == nil {
			continue
		}
		if err := os.MkdirAll(c.host(d), 0755); err != nil {
			return err
		}
		if err := recordCreated(c, createdDirs, d); err != nil {
			return err
		}
	}
	return nil
}

// removeCreatedDirs removes the directories in the created-dirs list if
// they are empty.
func removeCreatedDirs(c *config) {
	data, err := os.ReadFile(createdListFile(c, createdDirs))
	if err != nil {
		return
	}
	for _, d := range strings.Fields(string(data)) {
		if err := os.Remove(c.host(d)); err != nil && !errors.Is(err, os.ErrNotExist) {
			log.Printf("not removing %s: %v", d, err)
		}
	}
	os.Remove(createdListFile(c, createdDirs))
}

// containerdConfigVersion returns the version of the containerd config.
func containerdConfigVersion(c *config) (int, error) {
	data, err := os.ReadFile(c.host(c.rt.versionPath))
	if err != nil {
		return 0, fmt.Errorf("cannot read containerd config (nodes without a config file are not supported yet): %w", err)
	}
	v, err := configVersion(string(data))
	if err != nil {
		return 0, err
	}
	if v == 0 {
		return 0, fmt.Errorf("%s has no version key (version 1 config): not supported", c.rt.versionPath)
	}
	return v, nil
}

// editContainerdConfig applies edit to the config file that the installer
// edits, and reports whether the file changed. If the file does not exist
// and the setup has base content for it, the installer creates it.
func editContainerdConfig(c *config, edit func(string) (string, error)) (bool, error) {
	path := c.host(c.rt.configPath)
	mode := os.FileMode(0644)
	data, err := os.ReadFile(path)
	created := false
	if errors.Is(err, os.ErrNotExist) {
		if c.rt.baseContent == "" {
			return false, nil
		}
		data, created = []byte(c.rt.baseContent), true
	} else if err != nil {
		return false, err
	} else {
		mode = fileMode(path)
	}
	out, err := edit(string(data))
	if err != nil {
		return false, fmt.Errorf("cannot edit %s: %w", c.rt.configPath, err)
	}
	if created && out == c.rt.baseContent {
		return false, nil
	}
	if created {
		if err := recordCreated(c, createdFiles, c.rt.configPath); err != nil {
			return false, err
		}
	}
	changed, err := writeFileIfChanged(path, []byte(out), mode)
	if changed {
		log.Printf("updated %s", c.rt.configPath)
	}
	return changed, err
}

// removeCreatedFiles removes the config files that the installer created,
// if they only have their base content.
func removeCreatedFiles(c *config) {
	data, err := os.ReadFile(createdListFile(c, createdFiles))
	if err != nil {
		return
	}
	for _, f := range strings.Fields(string(data)) {
		if f == c.rt.configPath && readFileOrEmpty(c.host(f)) == c.rt.baseContent {
			if err := os.Remove(c.host(f)); err != nil {
				log.Printf("cannot remove %s: %v", f, err)
			}
		} else {
			log.Printf("not removing %s: it changed", f)
		}
	}
	os.Remove(createdListFile(c, createdFiles))
}

// hostCommand runs a command in the host's namespaces. It needs hostPID.
func hostCommand(c *config, args ...string) (string, error) {
	cmd := exec.Command("nsenter", append([]string{"--target=1", "--mount", "--uts", "--ipc", "--net", "--pid", "--"}, args...)...)
	out, err := cmd.CombinedOutput()
	if err != nil {
		return string(out), fmt.Errorf("%v: %w: %s", args, err, out)
	}
	return string(out), nil
}

// restartRuntime restarts containerd and waits until its CRI plugin is
// healthy. A config error can make containerd start without the CRI plugin,
// which takes the node down. If the setup generates the containerd config,
// restartRuntime also checks that the generated config has the
// gvisor-deploy block if and only if wantBlock is set.
func restartRuntime(c *config, wantBlock bool) error {
	log.Printf("restarting container runtime: %v", c.rt.restartCmd)
	if _, err := hostCommand(c, c.rt.restartCmd...); err != nil {
		return err
	}
	if err := waitHealthy(c, readyTimeout); err != nil {
		return err
	}
	if c.rt.effectivePath != "" {
		if has := strings.Contains(readFileOrEmpty(c.host(c.rt.effectivePath)), blockBegin); has != wantBlock {
			return fmt.Errorf("generated config %s: gvisor-deploy block present=%v, want %v", c.rt.effectivePath, has, wantBlock)
		}
	}
	log.Printf("containerd CRI plugin is healthy")
	return nil
}

// waitHealthy waits until c.healthy succeeds, for at most timeout.
func waitHealthy(c *config, timeout time.Duration) error {
	deadline := time.Now().Add(timeout)
	for {
		err := c.healthy(c)
		if err == nil {
			return nil
		}
		if !time.Now().Before(deadline) {
			return fmt.Errorf("containerd is not healthy after %v: %w", timeout, err)
		}
		time.Sleep(time.Second)
	}
}

// criHealthy checks that containerd answers on its socket and that its CRI
// plugin loaded, with the host's ctr tool.
func criHealthy(c *config) error {
	out, err := hostCommand(c, "ctr", "--address", c.rt.socket, "plugins", "ls")
	if err != nil {
		return err
	}
	for _, line := range strings.Split(out, "\n") {
		f := strings.Fields(line)
		if len(f) >= 3 && f[0] == "io.containerd.grpc.v1" && f[1] == "cri" {
			if f[len(f)-1] != "ok" {
				return fmt.Errorf("CRI plugin status: %s", line)
			}
			return nil
		}
	}
	return fmt.Errorf("CRI plugin not listed by ctr")
}

// artifactFiles returns the regular files under dir, relative to dir, in
// lexical order.
func artifactFiles(dir string) ([]string, error) {
	var files []string
	err := filepath.WalkDir(dir, func(p string, d os.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.Type().IsRegular() {
			rel, err := filepath.Rel(dir, p)
			if err != nil {
				return err
			}
			files = append(files, rel)
		} else if !d.IsDir() {
			return fmt.Errorf("unexpected non-regular file %s", p)
		}
		return nil
	})
	return files, err
}

// artifactsHash returns a short content hash of the release files to
// install: runsc, the shim, and the gvisor-bin/ helper binaries.
func artifactsHash(dir string) (string, error) {
	files, err := artifactFiles(dir)
	if err != nil {
		return "", err
	}
	h := sha256.New()
	for _, rel := range files {
		f, err := os.Open(filepath.Join(dir, rel))
		if err != nil {
			return "", err
		}
		fmt.Fprintf(h, "%s\x00", rel)
		_, err = io.Copy(h, f)
		f.Close()
		if err != nil {
			return "", err
		}
	}
	return hex.EncodeToString(h.Sum(nil))[:16], nil
}

// copyTree copies the release files from src to dst. runsc expects
// gvisor-bin/ next to its own binary, so the layout is kept.
func copyTree(src, dst string) error {
	files, err := artifactFiles(src)
	if err != nil {
		return err
	}
	for _, rel := range files {
		if err := copyFileAtomic(filepath.Join(src, rel), filepath.Join(dst, rel), 0755); err != nil {
			return err
		}
	}
	return nil
}

func copyFileAtomic(src, dst string, mode os.FileMode) error {
	if err := os.MkdirAll(filepath.Dir(dst), 0755); err != nil {
		return err
	}
	in, err := os.Open(src)
	if err != nil {
		return err
	}
	defer in.Close()
	tmp, err := os.CreateTemp(filepath.Dir(dst), ".tmp-"+filepath.Base(dst))
	if err != nil {
		return err
	}
	defer os.Remove(tmp.Name())
	if _, err := io.Copy(tmp, in); err != nil {
		tmp.Close()
		return err
	}
	if err := tmp.Chmod(mode); err != nil {
		tmp.Close()
		return err
	}
	if err := tmp.Sync(); err != nil {
		tmp.Close()
		return err
	}
	if err := tmp.Close(); err != nil {
		return err
	}
	return os.Rename(tmp.Name(), dst)
}

// writeFileIfChanged atomically writes data to path if its content differs.
func writeFileIfChanged(path string, data []byte, mode os.FileMode) (bool, error) {
	if old, err := os.ReadFile(path); err == nil && string(old) == string(data) {
		return false, nil
	}
	if err := os.MkdirAll(filepath.Dir(path), 0755); err != nil {
		return false, err
	}
	tmp, err := os.CreateTemp(filepath.Dir(path), ".tmp-"+filepath.Base(path))
	if err != nil {
		return false, err
	}
	defer os.Remove(tmp.Name())
	if _, err := tmp.Write(data); err != nil {
		tmp.Close()
		return false, err
	}
	if err := tmp.Chmod(mode); err != nil {
		tmp.Close()
		return false, err
	}
	if err := tmp.Close(); err != nil {
		return false, err
	}
	return true, os.Rename(tmp.Name(), path)
}

func symlinkAtomic(target, link string) error {
	tmp := link + ".tmp"
	os.Remove(tmp)
	if err := os.Symlink(target, tmp); err != nil {
		return err
	}
	return os.Rename(tmp, link)
}

// inUseFiles returns the (device, inode) pairs of all running executables.
// With hostPID, /proc lists all host processes.
func inUseFiles() map[[2]uint64]bool {
	used := make(map[[2]uint64]bool)
	procs, _ := filepath.Glob("/proc/[0-9]*/exe")
	for _, p := range procs {
		var st syscall.Stat_t
		if err := syscall.Stat(p, &st); err == nil {
			used[[2]uint64{uint64(st.Dev), st.Ino}] = true
		}
	}
	return used
}

func versionInUse(c *config, dir string, used map[[2]uint64]bool) bool {
	files, _ := artifactFiles(c.host(dir))
	for _, rel := range files {
		var st syscall.Stat_t
		if err := syscall.Stat(c.host(filepath.Join(dir, rel)), &st); err == nil && used[[2]uint64{uint64(st.Dev), st.Ino}] {
			return true
		}
	}
	return false
}

func countSandboxes(c *config) int {
	used := inUseFiles()
	n := 0
	dirs, _ := os.ReadDir(c.host(filepath.Join(c.installDir, versionsDir)))
	for _, d := range dirs {
		if versionInUse(c, filepath.Join(c.installDir, versionsDir, d.Name()), used) {
			n++
		}
	}
	return n
}

// gcVersions removes installed versions other than keep that no running
// process uses.
func gcVersions(c *config, keep string) {
	used := inUseFiles()
	root := filepath.Join(c.installDir, versionsDir)
	dirs, _ := os.ReadDir(c.host(root))
	for _, d := range dirs {
		if d.Name() == keep || strings.HasPrefix(d.Name(), stagingPrefix) {
			continue
		}
		dir := filepath.Join(root, d.Name())
		if versionInUse(c, dir, used) {
			log.Printf("keeping %s: still in use", dir)
			continue
		}
		// Rename first: a version directory that exists is complete.
		trash := filepath.Join(root, trashPrefix+d.Name())
		if err := os.Rename(c.host(dir), c.host(trash)); err != nil {
			log.Printf("cannot remove %s: %v", dir, err)
			continue
		}
		log.Printf("removed unused version %s", dir)
	}
	trash, _ := filepath.Glob(c.host(filepath.Join(root, trashPrefix+"*")))
	for _, t := range trash {
		if err := os.RemoveAll(t); err != nil {
			log.Printf("cannot remove %s: %v", t, err)
		}
	}
}

// triggerUninstall switches the DaemonSet pods to uninstall mode through a
// rolling update, then waits until every pod has finished uninstalling.
func triggerUninstall(ns, name string) error {
	if ns == "" || name == "" {
		return fmt.Errorf("DAEMONSET_NAMESPACE and DAEMONSET_NAME must be set")
	}
	kube, err := newKubeClient()
	if err != nil {
		return err
	}
	patch := map[string]any{"spec": map[string]any{
		"updateStrategy": map[string]any{"type": "RollingUpdate", "rollingUpdate": map[string]any{"maxUnavailable": "100%"}},
		"template":       map[string]any{"metadata": map[string]any{"annotations": map[string]any{modeAnnot: "uninstall"}}},
	}}
	if err := kube.patchDaemonSet(ns, name, patch); err != nil {
		return err
	}
	log.Printf("switched DaemonSet %s/%s to uninstall mode; waiting for all nodes", ns, name)
	// Stay under the default Helm timeout (5m), so that the error below is
	// what the user sees.
	deadline := time.Now().Add(4*time.Minute + 30*time.Second)
	for time.Now().Before(deadline) {
		time.Sleep(3 * time.Second)
		ds, err := kube.getDaemonSet(ns, name)
		if err != nil {
			log.Printf("cannot get DaemonSet: %v", err)
			continue
		}
		s := ds.Status
		log.Printf("desired=%d updated=%d ready=%d", s.DesiredNumberScheduled, s.UpdatedNumberScheduled, s.NumberReady)
		if s.ObservedGeneration >= ds.Metadata.Generation && s.UpdatedNumberScheduled == s.DesiredNumberScheduled && s.NumberReady == s.DesiredNumberScheduled && s.NumberUnavailable == 0 {
			log.Printf("all nodes uninstalled")
			return nil
		}
	}
	return fmt.Errorf("timed out waiting for all nodes to uninstall; check the logs of the installer pods that are not ready. To remove the release without cleaning the nodes, run `helm uninstall --no-hooks`")
}
